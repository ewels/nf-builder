/** Whether a file name's extension marks it as binary, so it needn't be downloaded (IO-12). */
export function binaryByName(path: string): boolean {
  const name = path.slice(path.lastIndexOf("/") + 1);
  const dot = name.lastIndexOf(".");
  return dot > 0 && BINARY_EXTENSIONS.has(name.slice(dot + 1).toLowerCase());
}
