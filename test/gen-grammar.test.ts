import { cpSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join } from "node:path";
import { describe, expect, it } from "vitest";
import { REPO_ROOT } from "../scripts/check-common.ts";
import {
  applyPort,
  checkGenerated,
  generatedHeader,
  packDir,
  readUpstream,
} from "../scripts/gen-grammar.ts";

const VERSION = "26.10";
const PACK = packDir(VERSION);
const read = (file: string) => readFileSync(join(PACK, file), "utf8");

// The pack's port table is data (grammar/port.ts); load it as the generator does.
const { PORT } = (await import(join(PACK, "grammar", "port.ts"))) as {
  PORT: Record<
    string,
    {
      header: { java: string; ts: string; occurrences: number };
      members: { java: string; ts: string; occurrences: number };
      actions: { java: string; ts: string; occurrences: number }[];
    }
  >;
};

describe("gen:grammar", () => {
  it("F-101 step 2 ADR-0005: pnpm gen:grammar 26.10 regenerates packages/lang-2610/src/generated byte-identically", async () => {
    const { differences } = await checkGenerated({
      version: VERSION,
    });
    expect(differences).toEqual([]);
  }, 60_000);

  it("F-101 step 3 ADR-0005: every generated file starts with a do-not-edit header naming the upstream tag and commit", () => {
    const upstream = readUpstream(PACK);
    const antlrNg = (
      JSON.parse(
        readFileSync(
          join(REPO_ROOT, "node_modules/antlr-ng/package.json"),
          "utf8",
        ),
      ) as { version: string }
    ).version;
    for (const name of [
      "ScriptLexer",
      "ScriptParser",
      "ConfigLexer",
      "ConfigParser",
    ]) {
      const text = read(`src/generated/${name}.ts`);
      const header = generatedHeader({
        version: VERSION,
        packRel: "packages/lang-2610",
        grammarFile: `${name}.g4`,
        path: upstream.grammar.path,
        tag: upstream.nextflow.tag,
        commit: upstream.nextflow.commit,
        antlrNg,
        noCheck: text.includes("// @ts-nocheck\n"),
      });
      expect(text.startsWith(header), name).toBe(true);
      expect(header).toContain(upstream.nextflow.tag);
      expect(header).toContain(upstream.nextflow.commit);
      expect(header).toContain("Do not edit");
    }
  });

  it("ADR-0005: the generator stops when a Java action has no TypeScript port, naming the grammar file", () => {
    const grammar = `${read("grammar/ScriptLexer.g4")}\nEXTRA : 'x' { foo(); } ;\n`;
    expect(() =>
      applyPort(grammar, PORT.ScriptLexer as never, "ScriptLexer.g4"),
    ).toThrow(/ScriptLexer\.g4.*Java left in grammar/s);
  });

  it("ADR-0005: the generator stops when a port entry no longer matches the grammar", () => {
    const grammar = read("grammar/ScriptLexer.g4");
    const port = PORT.ScriptLexer as NonNullable<(typeof PORT)[string]>;
    const first = port.actions[0] as (typeof port.actions)[number];
    const changedText = {
      ...port,
      actions: [{ ...first, java: `${first.java} // changed` }],
    };
    expect(() =>
      applyPort(grammar, changedText as never, "ScriptLexer.g4"),
    ).toThrow(/ScriptLexer\.g4: port entry not found or count changed/);
    const changedCount = {
      ...port,
      actions: [{ ...first, occurrences: first.occurrences + 1 }],
    };
    expect(() =>
      applyPort(grammar, changedCount as never, "ScriptLexer.g4"),
    ).toThrow(/port entry not found or count changed/);
  });

  it("ADR-0005: gen:grammar rejects a version without a pack and lists the packs", () => {
    expect(() => packDir("99.99")).toThrow(/26\.10/);
  });

  it("ADR-0005: gen:grammar --check reports a hand edit of a generated file", async () => {
    const root = mkdtempSync(join(tmpdir(), "gen-grammar-"));
    const copy = join(root, "packages", basename(PACK));
    for (const part of ["grammar", "upstream.json", "src/generated"]) {
      cpSync(join(PACK, part), join(copy, part), { recursive: true });
    }
    const file = join(copy, "src/generated/ScriptLexer.ts");
    writeFileSync(file, `${readFileSync(file, "utf8")}// hand edit\n`);
    const { differences } = await checkGenerated({
      version: VERSION,
      repoRoot: root,
    });
    expect(differences.join("\n")).toContain("ScriptLexer.ts");
  }, 60_000);
});
