const fulfil = (
  route: Route,
  reply: Reply,
  base: Record<string, string>,
): Promise<void> =>
  route.fulfill({
    status: reply.status,
    headers: { ...base, ...reply.headers },
    body: reply.body ?? "",
  });

const json = (status: number, body: unknown): Reply => ({
  status,
  headers: { "content-type": "application/json; charset=utf-8" },
  body: JSON.stringify(body),
});

/** Answers api.github.com and raw.githubusercontent.com from `repos`; the log says what was asked for. */
export async function mockGithub(
  page: Page,
  repos: readonly MockRepo[],
  overrides: Overrides = {},
): Promise<GithubLog> {
  const log: GithubLog = { api: [], raw: [], unexpected: [] };
  await page.route("https://api.github.com/**", (route) => {
    const url = new URL(route.request().url());
    const key = `${url.pathname}${url.search}`;
    log.api.push(key);
    const over = overrides.api?.(key);
    if (over) return fulfil(route, over, API_HEADERS);
    const m = /^\/repos\/([^/]+\/[^/]+)\/(commits|git\/trees)\/(.+)$/.exec(
      url.pathname,
    );
    const repo = repos.find((r) => r.repo === m?.[1]);
    if (!m || !repo) {
      log.unexpected.push(key);
      return fulfil(route, json(404, { message: "Not Found" }), API_HEADERS);
    }
    const id = decodeURIComponent(m[3] ?? "");
    if (m[2] === "commits") {
      const sha = repo.refs[id];
      return sha
        ? fulfil(route, { status: 200, body: sha }, API_HEADERS)
        : fulfil(route, json(422, { message: "No commit found" }), API_HEADERS);
    }
    if (id !== repo.sha || url.search !== "?recursive=1") {
      log.unexpected.push(key);
      return fulfil(route, json(404, { message: "Not Found" }), API_HEADERS);
    }
    return fulfil(route, json(200, repo.tree), API_HEADERS);
  });
  await page.route("https://raw.githubusercontent.com/**", async (route) => {
    const url = new URL(route.request().url());
    const [owner, name, sha, ...rest] = url.pathname.split("/").slice(1);
    const path = rest.map(decodeURIComponent).join("/");
    log.raw.push(path);
    const over = await overrides.raw?.(path);
    if (over) return fulfil(route, over, RAW_HEADERS);
    const repo = repos.find((r) => r.repo === `${owner}/${name}`);
    const bytes = repo && sha === repo.sha ? repo.raw(path) : null;
    if (bytes === null || bytes === undefined) {
      log.unexpected.push(url.pathname);
      return fulfil(
        route,
        { status: 404, body: "404: Not Found" },
        RAW_HEADERS,
      );
    }
    // like the real host: gzip hidden by CORS, so content-length counts fewer bytes than the body and no content-encoding shows
    const headers: Record<string, string> =
      bytes.length > 1 ? { "content-length": String(bytes.length - 1) } : {};
    return fulfil(route, { status: 200, headers, body: bytes }, RAW_HEADERS);
  });
  return log;
}
